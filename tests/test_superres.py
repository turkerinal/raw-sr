def test_srresult_exposes_alignment_quality():
    frames, _ = _burst([(0.0, 0.0), (0.4, 0.0), (0.0, 0.4), (0.7, 0.5)])
    res = SuperResolution(ratio=2.0, blur_threshold_ratio=0.0).run(frames)
    n = res.used_frames
    assert len(res.kept_indices) == n
    assert len(res.align_scores) == n
    assert len(res.align_residuals) == n
    # kept_indices index back into the input list, in order, unique, in range.
    assert res.kept_indices == sorted(set(res.kept_indices))
    assert all(0 <= i < res.total_frames for i in res.kept_indices)
    # The reference frame is always kept and scores a perfect 1.0. The
    # reference is selected automatically (sharpest frame near the burst
    # centroid) and reported in metrics["reference_index"].
    ref_index = res.metrics["reference_index"]
    assert ref_index in res.kept_indices
    ref = res.kept_indices.index(ref_index)
    assert res.align_scores[ref] == 1.0
    assert res.align_residuals[ref] == 0.0
    # Scores are ZNCC in [0, 1], residuals are finite and non-negative.
    assert all(0.0 <= s <= 1.0 for s in res.align_scores)
    assert all(np.isfinite(r) and r >= 0.0 for r in res.align_residuals)
    # Lists are aligned with the other per-kept-frame outputs.
    assert len(res.transforms) == n and len(res.shifts) == n
    # D2: exactly the reference is flagged as a self-comparison.
    assert len(res.align_self) == n
    assert sum(bool(v) for v in res.align_self) == 1
    assert res.align_self[ref] is True


def test_reference_self_comparison_excluded_from_aggregates():
    # D2: the reference's trivial 1.0/0.0 self-comparison must not enter the
    # mean/max aggregates; the lists themselves keep the value (key count).
    frames, _ = _burst([(0.0, 0.0), (0.4, 0.0), (0.0, 0.4), (0.7, 0.5),
                        (0.2, 0.6)])
    res = SuperResolution(ratio=2.0, blur_threshold_ratio=0.0).run(frames)
    ns = [i for i, b in enumerate(res.align_self) if not b]
    assert len(ns) == res.used_frames - 1
    assert np.isclose(res.metrics["mean_align_score"],
                      float(np.mean([res.align_scores[i] for i in ns])))
    assert np.isclose(res.metrics["align_residual_mean_px"],
                      float(np.mean([res.align_residuals[i] for i in ns])))
    assert np.isclose(res.metrics["align_residual_max_px"],
                      float(np.max([res.align_residuals[i] for i in ns])))
    # And the self value would have changed the mean (proves exclusion matters).
    all_mean = float(np.mean(res.align_residuals))
    assert not np.isclose(res.metrics["align_residual_mean_px"], all_mean)


def test_opencl_metrics_are_semantically_consistent():
    # D3: opencl_active is True iff EITHER engine used the GPU; opencl_warp
    # reports the warp decision alone and is always present.
    frames, _ = _burst([(0.0, 0.0), (0.4, 0.0), (0.0, 0.4)])
    res = SuperResolution(ratio=2.0, ibp_iterations=0,
                          use_opencl=False, use_gpu_scatter=False).run(frames)
    assert res.metrics["opencl_warp"] is False
    assert res.metrics["opencl_scatter"] == "cpu"
    assert res.metrics["opencl_active"] is False
    assert res.metrics["opencl_active"] == (
        res.metrics["opencl_warp"] or res.metrics["opencl_scatter"] == "gpu")
    assert isinstance(res.metrics["opencl_warp"], bool)


def test_alignment_gate_rejects_a_misaligned_frame():
    # 192 LR px is the smallest frame on which the gate can separate a junk
    # frame from correctly registered aliased content; below it the gate is
    # advisory by design (review round 2, N2), so the fixture must be this big.
    good, _ = _burst([(0.0, 0.0), (0.4, 0.0), (0.0, 0.4), (0.5, 0.5)],
                     truth=_random_truth(384, 384))
    rng = np.random.default_rng(123)
    bad = RawFrame(name="bad",
                   rgb=rng.random((good[0].rgb.shape), dtype=np.float32),
                   green=rng.random(good[0].green.shape, dtype=np.float32))
    frames = good + [bad]
    res = SuperResolution(ratio=2.0, blur_threshold_ratio=0.0,
                          min_align_score=0.5).run(frames)
    assert res.used_frames < res.total_frames
    assert 4 not in res.kept_indices, "misaligned frame was not gated out"
    assert 0 in res.kept_indices, "reference frame must always be kept"
    assert all(s >= 0.5 for s in res.align_scores)


