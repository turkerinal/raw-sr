# D1: the phase-correlation response is gated. A failed correlation (measured
# response 0.0017 on frame 8 of the real burst) used to be accepted verbatim,
# reporting a bogus ~23 px shift; below the threshold estimate_translation must
# fall back to template matching (and be honest when that finds no structure).
