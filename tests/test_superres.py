def test_load_raw_linear_passes_demosaic_algorithm(monkeypatch):
    import rawpy

    captured = {}

    class _FakeRaw:
        black_level_per_channel = [0, 0, 0, 0]
        white_level = 65535
        camera_whitebalance = [1.0, 1.0, 1.0, 1.0]
        raw_image = np.zeros((4, 4), dtype=np.uint16)

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

        def postprocess(self, **kwargs):
            captured.update(kwargs)
            return np.zeros((2, 2, 3), dtype=np.uint16)

    monkeypatch.setattr(rawpy, "imread", lambda path: _FakeRaw())

    # Default must be the sharper DCB demosaic.
    load_raw_linear("fake.dng")
    assert captured.get("demosaic_algorithm") == rawpy.DemosaicAlgorithm.DCB
    assert captured.get("gamma") == (1, 1)
    assert captured.get("no_auto_bright") is True

    # And it must be overridable.
    load_raw_linear("fake.dng",
                    demosaic_algorithm=rawpy.DemosaicAlgorithm.AHD)
    assert captured.get("demosaic_algorithm") == rawpy.DemosaicAlgorithm.AHD



