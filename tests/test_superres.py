def test_translation_sign_convention():
    truth = _random_truth()
    ref = _sample_lr(truth, 0.0, 0.0, (128, 128))
    mov = _sample_lr(truth, 0.7, -0.4, (128, 128))
    dx, dy = estimate_translation(ref[:, :, 1], mov[:, :, 1])
    assert abs(dx - 0.7) < 0.15, f"dx={dx} expected ~0.7"
    assert abs(dy - (-0.4)) < 0.15, f"dy={dy} expected ~-0.4"


def test_translation_zero_is_zero():
    truth = _random_truth(128, 128)
    a = _sample_lr(truth, 0.0, 0.0, (64, 64))
    dx, dy = estimate_translation(a[:, :, 1], a[:, :, 1])
    assert abs(dx) < 0.05 and abs(dy) < 0.05


