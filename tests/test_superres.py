def test_run_rejects_nan_or_inf_frames():
    frames = _plain_frames(2)
    sr = SuperResolution(ratio=2.0)
    frames[1].green[3, 4] = np.nan
    with pytest.raises(ValueError, match="frame 1 contains NaN or Inf in green"):
        sr.run(frames)
    frames = _plain_frames(2)
    frames[0].rgb[2, 2, 0] = np.inf
    with pytest.raises(ValueError, match="frame 0 contains NaN or Inf in rgb"):
        sr.run(frames)


def test_run_rejects_mismatched_frame_shapes():
    frames = _plain_frames(3)
    small = frames[2].rgb[:20, :22].copy()
    frames[2] = RawFrame(name="f2", rgb=small, green=small[:, :, 1].copy())
    sr = SuperResolution(ratio=2.0)
    with pytest.raises(ValueError, match="must share one ROI and shape"):
        sr.run(frames)


