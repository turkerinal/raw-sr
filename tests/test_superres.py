def test_phase_corr_threshold_is_documented_and_separates_populations():
    # Good locks on the real burst measured 0.55-1.00, the failure 0.0017.
    assert _PHASE_CORR_MIN_RESPONSE == 0.1
    assert 0.0017 < _PHASE_CORR_MIN_RESPONSE < 0.55


def test_estimate_translation_keeps_phase_result_above_threshold(monkeypatch):
    def fake_pc(a, b, win=None):
        return (1.234, -5.678), 0.5   # a confident lock

    monkeypatch.setattr(cv2, "phaseCorrelate", fake_pc)
    dx, dy = estimate_translation(np.zeros((64, 64), np.float32),
                                  np.zeros((64, 64), np.float32))
    # Returned sign is negated relative to cv2.phaseCorrelate.
    assert np.isclose(dx, -1.234) and np.isclose(dy, 5.678)


def test_estimate_translation_falls_back_to_template_on_low_response(monkeypatch):
    truth = _random_truth(192, 192)
    ref = _sample_lr(truth, 0.0, 0.0, (96, 96))[:, :, 1]
    mov = _sample_lr(truth, 0.9, -0.6, (96, 96))[:, :, 1]

    def fake_pc(a, b, win=None):
        return (18.0, -9.0), 0.0017   # failed correlation, bogus shift

    monkeypatch.setattr(cv2, "phaseCorrelate", fake_pc)
    dx, dy = estimate_translation(ref, mov)
    # Template matching must recover the true (0.9, -0.6), not the bogus value.
    assert np.hypot(dx - 0.9, dy + 0.6) < 0.35, f"fallback gave ({dx:.3f},{dy:.3f})"
    assert not (abs(dx + 18.0) < 1.0 and abs(dy - 9.0) < 1.0)


def test_estimate_translation_low_response_without_structure_is_zero(monkeypatch):
    def fake_pc(a, b, win=None):
        return (9.0, 9.0), 0.0

    monkeypatch.setattr(cv2, "phaseCorrelate", fake_pc)
    # Flat frames carry no structure: the template match has no trustworthy
    # peak and the honest answer is (0, 0) rather than an arbitrary shift.
    dx, dy = estimate_translation(np.zeros((64, 64), np.float32),
                                  np.zeros((64, 64), np.float32))
    assert dx == 0.0 and dy == 0.0


def test_estimate_translation_fallback_does_not_mutate_inputs(monkeypatch):
    truth = _random_truth(160, 160)
    a = _sample_lr(truth, 0.0, 0.0, (80, 80))[:, :, 1]
    b = _sample_lr(truth, 0.5, 0.5, (80, 80))[:, :, 1]
    a_before, b_before = a.copy(), b.copy()

    monkeypatch.setattr(cv2, "phaseCorrelate",
                        lambda x, y, w=None: ((7.0, -7.0), 0.0))
    estimate_translation(a, b)
    assert np.array_equal(a, a_before) and np.array_equal(b, b_before)


