def test_translation_matrix_and_drizzle_matrix_convention():
    W = translation_matrix(0.5, -0.25)
    assert np.allclose(W[:2, 2], [0.5, -0.25])
    M = to_drizzle_matrix((0.5, -0.25), 2.0)
    # M = T((r-1)/2) @ diag(ratio, ratio, 1) @ inv(W): maps LR src coords to
    # pixel-centre-aligned HR dst coords. inv(W) gives (-0.5, +0.25) LR, times
    # ratio (-1.0, +0.5) HR, plus the 0.5 HR centre offset.
    assert np.isclose(M[0, 0], 2.0) and np.isclose(M[1, 1], 2.0)
    assert np.isclose(M[0, 2], -0.5) and np.isclose(M[1, 2], 1.0)


def test_homography_recovers_known_translation():
    truth = _random_truth()
    ref = _sample_lr(truth, 0.0, 0.0, (128, 128))
    W_true = translation_matrix(0.8, -0.5)
    # Build mov so that mov(W_true(p)) == ref(p): mov(p) = ref(W_true^-1 p).
    mov = cv2.warpPerspective(ref, W_true.astype(np.float32),
                              (128, 128), flags=cv2.INTER_LINEAR,
                              borderMode=cv2.BORDER_REPLICATE)
    W = estimate_homography(ref[:, :, 1], mov[:, :, 1], ecc_scale=0.5)
    assert abs(W[0, 2] - 0.8) < 0.2, f"tx={W[0, 2]}"
    assert abs(W[1, 2] - (-0.5)) < 0.2, f"ty={W[1, 2]}"


def test_homography_aligns_at_least_as_well_as_translation():
    truth = _random_truth(160, 160)
    ref = _sample_lr(truth, 0.0, 0.0, (80, 80))
    # A rotation + translation the translation-only model cannot express.
    W_true = np.array([[np.cos(0.04), -np.sin(0.04), 0.6],
                       [np.sin(0.04), np.cos(0.04), -0.4],
                       [0.0, 0.0, 1.0]])
    mov = cv2.warpPerspective(ref, W_true.astype(np.float32),
                              (80, 80), flags=cv2.INTER_LINEAR,
                              borderMode=cv2.BORDER_REPLICATE)
    ref_g, mov_g = ref[:, :, 1], mov[:, :, 1]
    dx, dy = estimate_translation(ref_g, mov_g)
    W_t = translation_matrix(-dx, -dy)
    W_h = estimate_homography(ref_g, mov_g, ecc_scale=0.5)
    s_t = _alignment_score(ref_g, mov_g, W_t)
    s_h = _alignment_score(ref_g, mov_g, W_h)
    assert s_h >= s_t - 1e-6
    # Translation cannot express the rotation, so homography must win clearly.
    assert s_h > s_t + 0.1, f"homography {s_h} not better than translation {s_t}"
    assert s_h > 0.8, f"homography alignment weak: {s_h}"


def test_scatter_preserves_more_high_frequency_than_a_gather():
    # An interpolated gather's reconstruction kernel has its first zero at the
    # single-frame Nyquist, so it low-passes the recovered >Nyquist band; the
    # scatter splat does not. Compare above-Nyquist energy directly.
    truth = _bandpass_truth()
    frames, _ = _burst(DIVERSE_SHIFTS, truth=truth, noise=0.0)
    hr_scatter, _ = drizzle(frames, _aligns(DIVERSE_SHIFTS), ratio=2.0)  # scatter default
    hr_gather, _ = drizzle(frames, _aligns(DIVERSE_SHIFTS), ratio=2.0,
                           deposit="gather", interp=cv2.INTER_LINEAR)
    gain = high_frequency_gain_db(to_view_float(hr_scatter, exposure=1.0),
                                  to_view_float(hr_gather, exposure=1.0))
    assert gain > 6.0, (
        f"scatter did not clearly beat the linear gather in the >Nyquist band "
        f"(gain {gain:.2f} dB)")
    # And it must reconstruct the known band better, not merely add energy.
    assert (np.mean((hr_scatter - truth) ** 2)
            < np.mean((hr_gather - truth) ** 2))


