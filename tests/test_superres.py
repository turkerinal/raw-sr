def test_drizzle_output_shape_and_coverage():
    frames, _ = _burst([(0, 0), (0.5, 0.0), (0.0, 0.5)])
    hr, cov = drizzle(frames, _aligns([(0, 0), (0.5, 0), (0, 0.5)]), ratio=2.0)
