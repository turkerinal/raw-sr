"""Failing-first tests for the genuine multi-frame SR core (superres.py).

Self-contained: synthetic LR frames are generated by sampling a known HR
ground truth with subpixel shifts, so the correct answer is known and the
metrics can be checked against truth.

Evidence framing (mission = "upscale RAW photos"):
- "naive" = bicubic upsampling of a single frame (what a plain upscaler does).
- SR must reconstruct the HR scene measurably better than the naive upscale,
  including genuine high-frequency content above the single-frame Nyquist.
"""

