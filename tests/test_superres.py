def _random_truth(h=256, w=256, seed=7, sigma=0.6):
    rng = np.random.default_rng(seed)
    t = rng.random((h, w, 3)).astype(np.float32)
    return cv2.GaussianBlur(t, (0, 0), sigma)


def _bandpass_truth(h=256, w=256, lo=0.30, hi=0.50, seed=7):
    """Truth whose energy sits ABOVE the LR Nyquist (0.25 cyc/HR-px).

    A single bicubic-upscaled frame cannot invent this band; only the
    subpixel phase diversity of a burst can recover it.
    """
    rng = np.random.default_rng(seed)
    g = rng.random((h, w)).astype(np.float32)
    F = np.fft.fftshift(np.fft.fft2(g))
    fy = np.fft.fftshift(np.fft.fftfreq(h))[:, None]
    fx = np.fft.fftshift(np.fft.fftfreq(w))[None, :]
    r = np.sqrt(fx ** 2 + fy ** 2)
    F[(r < lo) | (r > hi)] = 0
    g = np.real(np.fft.ifft2(np.fft.ifftshift(F))).astype(np.float32)
    g = (g - g.min()) / (g.max() - g.min() + 1e-9)
    return np.stack([g, g, g], axis=2)


def _sample_lr(truth, dx, dy, lr_shape):
    """Sample an LR frame: LR(x,y) = truth(r*(x+dx)+(r-1)/2, r*(y+dy)+(r-1)/2).

    The ``(r-1)/2`` is the pixel-centre convention of the HR grid (see
    :func:`superres.to_drizzle_matrix`), so the fixture and the reconstruction
    live on the same grid.
    """
    ratio = truth.shape[0] // lr_shape[0]
    off = 0.5 * (ratio - 1.0)
    xs, ys = np.meshgrid(np.arange(lr_shape[1], dtype=np.float32),
                         np.arange(lr_shape[0], dtype=np.float32))
    return cv2.remap(truth, ratio * (xs + dx) + off,
                     ratio * (ys + dy) + off,
                     cv2.INTER_LINEAR)


def _burst(shifts, truth=None, noise=0.002, seed=1):
    truth = truth if truth is not None else _random_truth()
    h, w = truth.shape[0] // 2, truth.shape[1] // 2
    rng = np.random.default_rng(seed)
    frames = []
    for i, (dx, dy) in enumerate(shifts):
        lr = _sample_lr(truth, dx, dy, (h, w))
        lr = np.clip(lr + rng.normal(0, noise, lr.shape).astype(np.float32), 0, 1)
        frames.append(RawFrame(name=f"f{i}", rgb=lr, green=lr[:, :, 1].copy()))
    return frames, truth


def _naive_single(frames, out_shape):
    return cv2.resize(frames[0].rgb, (out_shape[1], out_shape[0]),
                      interpolation=cv2.INTER_CUBIC)


DIVERSE_SHIFTS = [(0.0, 0.0), (0.5, 0.0), (0.0, 0.5), (0.5, 0.5),
                  (0.25, 0.75), (0.75, 0.25), (0.3, 0.3), (0.7, 0.7),
                  (0.15, 0.6)]


def _aligns(shifts):
    """ref->mov transforms for a list of ``(dx, dy)`` sampling shifts.

    ``_sample_lr(truth, dx, dy)`` makes ``mov(x) = ref(x + d)``, so the
    ref->mov transform (``mov(W(p)) == ref(p)``) is ``translation(-d)``.
    """
    return [translation_matrix(-dx, -dy) for dx, dy in shifts]


