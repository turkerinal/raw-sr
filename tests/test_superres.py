def _plain_frames(n=3, h=24, w=26, seed=11):
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        rgb = cv2.GaussianBlur(rng.random((h, w, 3)).astype(np.float32),
                               (0, 0), 0.7)
        out.append(RawFrame(name=f"p{i}", rgb=rgb, green=rgb[:, :, 1].copy()))
    return out


def test_run_rejects_out_of_range_reference_index():
    frames = _plain_frames(3)
    sr = SuperResolution(ratio=2.0, blur_threshold_ratio=0.0)
    for bad in (-1, 3, 9):
        with pytest.raises(ValueError, match="reference_index .* out of range"):
            sr.run(frames, reference_index=bad)


