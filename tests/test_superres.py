def test_estimate_translation_does_not_mutate_inputs():
    truth = _random_truth()
    a = _sample_lr(truth, 0.0, 0.0, (64, 64))
    b = _sample_lr(truth, 0.7, -0.4, (64, 64))
    a_before = a.copy()
    b_before = b.copy()
    estimate_translation(a[:, :, 1], b[:, :, 1])
    assert np.array_equal(a, a_before), "estimate_translation mutated `ref`"
    assert np.array_equal(b, b_before), "estimate_translation mutated `mov`"


def test_superres_run_does_not_mutate_frames():
    frames, _ = _burst(DIVERSE_SHIFTS)
    before = [f.rgb.copy() for f in frames]
    SuperResolution(ratio=2.0, blur_threshold_ratio=0.0).run(frames)
    for i, f in enumerate(frames):
        assert np.array_equal(f.rgb, before[i]), f"frame {i} mutated by run()"


